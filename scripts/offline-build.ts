// Build step for offline use. After a production build it lists every file
// the build wrote (with a hash of its content) and writes the service worker,
// sw.js, at the root of the output folder: src/offline/sw.ts bundled into one
// classic script with that list built in. A changed file changes the list,
// so sw.js changes and the browser installs the new version.
//
// Runs from the Vite plugin below (vite.config.ts), or by hand on a folder:
//   node scripts/offline-build.ts dist
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import type { Plugin } from 'vite';
import { buildManifest, cacheNames, type PrecacheManifest } from '../src/offline/manifest.ts';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
/** The service worker's source. */
export const SW_ENTRY = join(ROOT, 'src', 'offline', 'sw.ts');

/** Every file under `outDir` (paths with "/", relative to it), with the first 16 hex digits of its SHA-256 and its size. */
export function listFiles(outDir: string): { url: string; hash: string; size: number }[] {
  const out: { url: string; hash: string; size: number }[] = [];
  const walk = (dir: string) => {
    for (const name of readdirSync(dir).sort()) {
      const full = join(dir, name);
      if (statSync(full).isDirectory()) walk(full);
      else {
        const bytes = readFileSync(full);
        out.push({ url: relative(outDir, full).split(sep).join('/'), hash: createHash('sha256').update(bytes).digest('hex').slice(0, 16), size: bytes.length });
      }
    }
  };
  walk(outDir);
  return out;
}

/** Bundles the service worker (TypeScript) into one classic script with the manifest built in. */
export async function bundleServiceWorker(manifest: PrecacheManifest): Promise<string> {
  const { build } = await import('vite');
  const result = await build({
    configFile: false,
    logLevel: 'warn',
    root: ROOT,
    publicDir: false,
    define: { __FITEE_PRECACHE__: JSON.stringify(manifest) },
    build: {
      write: false,
      // Readable on purpose: every line that runs on the phone can be audited.
      minify: false,
      sourcemap: false,
      emptyOutDir: false,
      copyPublicDir: false,
      target: 'es2022',
      lib: { entry: SW_ENTRY, formats: ['iife'], name: 'fiteeServiceWorker', fileName: () => 'sw.js' },
    },
  });
  const outputs = (Array.isArray(result) ? result : [result]).flatMap((r) => ('output' in r ? r.output : []));
  const chunk = outputs.find((o) => o.type === 'chunk');
  if (!chunk || chunk.type !== 'chunk') throw new Error('offline-build: bundling the service worker produced no code');
  if (/^\s*(import|export)\s/m.test(chunk.code)) throw new Error('offline-build: sw.js must be a classic script (no import or export)');
  const names = cacheNames(manifest);
  return [
    '// fitee service worker: generated by scripts/offline-build.ts from src/offline/sw.ts. Do not edit.',
    `// Version ${manifest.version}: ${manifest.app.length} app files (cache ${names.app}), ${manifest.pose.length} pose files (a cache each, named by the file's hash).`,
    chunk.code,
  ].join('\n');
}

/** Lists the files in `outDir` and writes `outDir/sw.js`. Returns the manifest. */
export async function writeServiceWorker(outDir: string): Promise<PrecacheManifest> {
  const manifest = buildManifest(listFiles(outDir));
  if (!manifest.app.some((e) => e.url === 'index.html')) throw new Error(`offline-build: no index.html in ${outDir}`);
  writeFileSync(join(outDir, 'sw.js'), await bundleServiceWorker(manifest));
  return manifest;
}

const mb = (bytes: number) => `${(bytes / 1e6).toFixed(2)} MB`;
export const summary = (m: PrecacheManifest) =>
  `sw.js: version ${m.version}; app ${m.app.length} files (${mb(m.app.reduce((n, e) => n + e.size, 0))}), pose ${m.pose.length} files (${mb(m.pose.reduce((n, e) => n + e.size, 0))})`;

/** Vite plugin: writes sw.js after every production build, into the configured output folder. */
export function offlineBuild(): Plugin {
  let outDir = '';
  return {
    name: 'fitee-offline',
    apply: 'build',
    configResolved(config) {
      // The worker only answers for its own origin, so the app's files must be served from it.
      if (/^[a-z][a-z0-9+.-]*:/i.test(config.base)) throw new Error(`offline-build: base must be a path on this site, not ${config.base}`);
      outDir = resolve(config.root, config.build.outDir);
    },
    async closeBundle() {
      const manifest = await writeServiceWorker(outDir);
      console.log(summary(manifest));
    },
  };
}

// By hand: node scripts/offline-build.ts <outDir>
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const dir = process.argv[2];
  if (!dir) {
    console.error('Usage: node scripts/offline-build.ts <outDir>');
    process.exit(1);
  }
  console.log(summary(await writeServiceWorker(resolve(dir))));
}
